const NORMALIZE_STOCK_NAME=value=>String(value??'')
  .normalize('NFKD').replace(/[\u0300-\u036f]/g,'')
  .toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();

const PH_STOCK_UNITS=new Set(['kg','g','L','ml','unit']);

export function extendPhilippineStockPickerCatalog(baseCatalog=[]){
  const result=baseCatalog.map(group=>({
    ...group,
    storage:{...(group.storage||{})},
    items:(group.items||[]).map(pair=>[...pair])
  }));
  const existing=new Set(result.flatMap(group=>(group.items||[]).map(([name])=>NORMALIZE_STOCK_NAME(name))));
  const include=(group,entry)=>{
    const [name,unit]=entry;
    if(!name||!PH_STOCK_UNITS.has(unit))return;
    const key=NORMALIZE_STOCK_NAME(name);
    if(existing.has(key))return;
    existing.add(key);
    group.items.push([name,unit]);
  };
  for(const [category,entries] of Object.entries(PH_STOCK_PICKER_ADDITIONS)){
    const group=result.find(g=>g.category===category);
    if(!group)continue;
    entries.forEach(entry=>include(group,entry));
  }
  for(const definition of PH_STOCK_PICKER_EXTRA_GROUPS){
    if(result.some(g=>g.category===definition.category))continue;
    const group={...definition,storage:{...definition.storage},items:[]};
    definition.items.forEach(entry=>include(group,entry));
    if(group.items.length)result.push(group);
  }
  return result;
}

// Returns canonical names/units only. Aliases are for lookup, never separate Inventory products.
export function searchPhilippineStockPicker(catalog,query,{limit=90}={}){
  const search=NORMALIZE_STOCK_NAME(query);
  if(!search)return[];
  const words=search.split(' ').filter(Boolean);
  const matches=[];
  for(const group of catalog||[]){
    for(const [name,unit] of group.items||[]){
      const key=NORMALIZE_STOCK_NAME(name);
      const keys=[key,...(PH_STOCK_PICKER_ALIASES[name]||[]).map(NORMALIZE_STOCK_NAME)];
      if(keys.some(text=>words.every(word=>text.includes(word)))){
        matches.push({name,unit,category:group.category});
        if(matches.length>=limit)return matches;
      }
    }
  }
  return matches;
}

const SHELLFISH_CAUTION_NAMES=new Set([
  'mussels','oysters talaba','clams halaan',
  'blue swimming crab alimasag','mud crab alimango'
]);

export function philippineStockPickerSafetyNote(name){
  if(!SHELLFISH_CAUTION_NAMES.has(NORMALIZE_STOCK_NAME(name)))return'';
  return 'Shellfish/crab: check current BFAR red-tide bulletins and Bacoor/Cavite sale restrictions before buying, storing or selling. Listing an ingredient does not confirm it is safe or permitted.';
}
